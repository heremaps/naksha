       init {
            // Validate sort orders form a contiguous range [0, N); done here, after all types have loaded.
            // Note: This order is used to sort members in storages.
            // We first want all fixed size items with 8 byte, then 4 bytes, 2 byte, 1 byte, then flexible types.
            val orders = ArrayList<Int>()
            val i = iterate(MemberType::class)
            while (i.hasNext()) orders.add(i.next().sortOrder)
            orders.sort()
            for (idx in orders.indices) {
                if (orders[idx] != idx) throw NakshaException(
                    INITIALIZATION_FAILED,
                    "MemberType sort orders must be contiguous starting at 0; expected $idx but found ${orders[idx]} (all sorted: $orders)"
                )
            }
        }
    }

    /**
     * The Kotlin type that generally represents this member type.
     *
     * Beware the for primitives technically smaller values are as well accepted, therefore use [isInstance] to test if a value is valid for a certain member type and not the `isInstance` method of this class!
     *
     * The intent for this property is debugging purpose, for example `"exepcted ${memberType.valueType.simpleName}"`, which may print something like `"expected Long"` or `"expected TagMap"`.
     * @since 3.0
     */
    var valuesType: KClass<*> = Any::class
        private set

    /**
     * The subtype of this class, so the specialized member type, for example [StringMember].
     * @since 3.0
     */
    var subtype: KClass<out Member> = Member::class
        private set

    /**
     * Tests if the given value is of this type.
     *
     * **Note**: For [TAG_MAP_FROM_TAG_LIST] the expectation is [TagList], **not** [TagMap]!
     * @param value the value to test.
     * @return `true` if the value is of this type; false otherwise.
     */
    fun isInstance(value: Any?): Boolean {
        return value != null && when (this) {
            BOOLEAN -> value is Boolean
            INT8 -> value is Byte
            INT16 -> value is Byte || value is Short
            INT32 -> value is Byte || value is Short || value is Int
            INT64 -> value is Byte || value is Short || value is Int || value is Long || value is Int64
            FLOAT32 -> value is Float
            FLOAT64 -> value is Float || value is Double
            STRING -> value is String
            BYTE_ARRAY -> value is ByteArray
            TUPLE_NUMBER -> value is TupleNumber
            SPATIAL -> value is SpGeometry
            TAG_MAP -> value is TagMap
            TAG_LIST -> value is TagList
            else -> false
        }
    }

    /**
     * Converts the given value into the expected format of the type or returns `null`. For example for [INT8] numbers will be cast into [Byte].
     * @param value the value to convert.
     * @param normalize only for [TAG_LIST], if the value should be normalized or are from a trusted source.
     * @return the converted value or `null`.
     * @since 3.0
     */
    @JvmOverloads
    fun convert(value: Any?, normalize: Boolean = true): Any? = when (this) {
        INT8 -> if (value is Number) value.toByte() else if (value is Int64) value.toByte() else null
        INT16 -> if (value is Number) value.toShort() else if (value is Int64) value.toShort() else null
        INT32 -> if (value is Number) value.toInt() else if (value is Int64) value.toInt() else null
        INT64 -> if (value is Number) value.toLong() else if (value is Int64) value.toLong() else null
        FLOAT32 -> if (value is Number) value.toFloat() else if (value is Int64) value.toFloat() else null
        FLOAT64 -> if (value is Number) value.toDouble() else if (value is Int64) value.toDouble() else null
        STRING -> value as? String ?: if (value is Char || value is CharSequence) value.toString() else null
        BYTE_ARRAY -> value as? ByteArray
        TUPLE_NUMBER -> value as? TupleNumber ?:
                        if (value is String) TupleNumber.fromString(value)
                        else if (value is ByteArray) TupleNumber.fromByteArray(value)
                        else null
        SPATIAL -> value as? SpGeometry ?:
                        if (value is String) fromJSON(value).proxy(SpGeometry::class)
                        else if (value is ByteArray) GeoUtil.fromTWKB(value)
                        else value.proxy(SpGeometry::class)
        TAG_LIST -> value as? TagList ?:
                    if (value is Array<*>) TagList.fromArray(value)
                    else if (value is String) fromJSON(value).proxy(TagList::class)
                    else value.proxy(TagList::class)
        TAG_MAP -> value as? TagMap ?:
                   if (value is String) fromJSON(value).proxy(TagMap::class)
                   else value.proxy(TagMap::class)
        else -> null
    }

    /**
     * The sort order of the type to ensure no padding is needed, so `INT8`, `FLOAT8`, `INT4`, `FLOAT4`, ...
     * @since 3.0
     */
    var sortOrder: Int = -1
        // Validated in the companion `init` block above; the setter must not call iterate() (re-entrant during init).
        private set
}
