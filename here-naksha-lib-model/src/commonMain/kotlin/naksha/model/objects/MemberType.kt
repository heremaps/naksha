/**
 * The type of [Member]. The type defines what the storage expects as value in the member book of the [Tuple][naksha.model.Tuple], either as _HEAP_ object or as binary.
 *
 * The member book is generated by the [encoder][naksha.model.Tuple.encodeFeature], which must produce the values in the defined [MemberType] from the given input feature _(for example [NakshaFeature])_.
 *
 * The [decoder][naksha.model.Tuple.decodeFeature] reverses this. It receives a [Tuple][naksha.model.Tuple] from the storage which contains the [Member] values in the defined [MemberType] and integrates them back into the output feature _(for example [NakshaFeature])_.
 *
 * - [BOOLEAN], [INT8], [INT16], [INT32], [INT64], [FLOAT32], [FLOAT64], [STRING], [BYTE_ARRAY] —> Primitives.
 * - [SPATIAL] —> A geometry represented in memory as [SpGeometry] and binary as [TWKB](https://github.com/TWKB/Specification/blob/master/twkb.md).
 * - [TAG_LIST] —> A list of strings _([TagList])_. The order is significant and guaranteed. The storage persists the list unmodified, so the element order is guaranteed to be preserved when reading back from the storage.
 * - [TAG_MAP] —> A map with keys being strings and values being primitives _([TagMap])_. The order of the key-value pairs is not guaranteed by the storage, when converted into a [Member].
 * @since 3.0
 */
@JsExport
class MemberType : JsEnum() {

    @Suppress("NON_EXPORTABLE_TYPE")
    override fun namespace(): KClass<out JsEnum> = MemberType::class

    override fun initClass() {}

