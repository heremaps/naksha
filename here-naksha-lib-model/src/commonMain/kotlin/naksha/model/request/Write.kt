    /**
     * Tests if this write modifies a catalog.
     *
     * @return `true` if this write modifies a catalog; `false` otherwise.
     * @since 3.0
     */
    fun isCatalogModification(): Boolean = catalogId == ADMIN_CATALOG_ID && collectionId == CATALOGS_COL_ID

    /**
     * Tests if this write modifies a collection.
     *
     * @return `true` if this write modifies a collection; `false` otherwise.
     * @since 3.0
     */
    fun isCollectionModification(): Boolean = collectionId == COLLECTIONS_COL_ID

    /**
     * Tests if this write modifies a book.
     *
     * @return `true` if this write modifies a book; `false` otherwise.
     * @since 3.0
     */
    fun isBookModification(): Boolean = catalogId == ADMIN_CATALOG_ID && collectionId == BOOKS_COL_ID

    /**
     * Tests if this write modifies a book.
     *
     * @return `true` if this write modifies a book; `false` otherwise.
     * @since 3.0
     */
    fun isTransactionModification(): Boolean = catalogId == ADMIN_CATALOG_ID && collectionId == TRANSACTIONS_COL_ID

    /**
     * Tests if this write modifies a feature within a collection.
     *
     * @return `true` if this write modifies a feature within a collection; `false` otherwise.
     * @since 3.0
     */
    fun isFeatureModification(): Boolean = !isCatalogModification()
            && !isCollectionModification()
            && !isBookModification()
            && !isTransactionModification()

    /**
     * Validate that this write is valid, invoked by [session's][naksha.model.ISession] before executing the writes. This is just a simple pre-validation, storages have to do final checks.
     *
     * @since 3.0
     * @see [atomic]
     * @see [WriteOp]
     * @throws NakshaException with error [NakshaError.ILLEGAL_STATE], if the write is invalid.
     */
    fun validate(): Write {
        // Writing into the admin-catalog means that we want to mutate administrative objects.
        if (catalogId == ADMIN_CATALOG_ID) {
            if (collectionId == CATALOGS_COL_ID) { // Mutation of catalog.
                CATALOG.verify(id.text)
            } else if (collectionId == BOOKS_COL_ID) { // Mutation of book.
                FeatureType.BOOK.verify(id.text)
            } else if (collectionId == COLLECTIONS_COL_ID) { // Mutation of collection.
                COLLECTION.verify(id.text)
            } else if (collectionId == TRANSACTIONS_COL_ID) { // Mutation of transaction.
                FeatureType.TRANSACTION.verify(id.text)
            } else {
                throw illegalArg("Write operation for invalid collection in admin catalog; id: '$id' ")
            }
            return this
        } else if (collectionId == COLLECTIONS_COL_ID) { // Mutation of collection in custom catalog.
            COLLECTION.verify(id.text)
        } else { // arbitrary feature is modified, we allow any identifier, as long as it is in valid range.
            CATALOG.verify(catalogId.text)
            COLLECTION.verify(catalogId.text)
            FEATURE.verify(id.text)
        }
        return this
    }
