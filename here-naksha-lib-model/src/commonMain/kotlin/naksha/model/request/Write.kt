    /**
     * The method should be called after the [databaseId], [catalogId], [collectionId], and [id] have been set. It should be invoked with the raw value read from the [TupleNumber][naksha.model.objects.StandardMembers.StandardMembers_C.TnMember] of the feature to write, see [Member.read][naksha.model.objects.Member.read].
     * @param value the raw value of the [TupleNumber][naksha.model.objects.StandardMembers.StandardMembers_C.TnMember] of the feature that should be modified, read via [Member.read][naksha.model.objects.Member.read].
     * @since 3.0
     * @see [version]
     */
    fun withTupleNumber(value: Any?): Write {
        val tn = value as? TupleNumber ?: if (value is String) TupleNumber.toTupleNumber(value) else null
        if (tn != null) {
            val databaseNumber = this.databaseId.number
            val catalogNumber = this.catalogId.intValue
            val collectionNumber = this.collectionId.intValue
            val featureNumber = this.id.number
            if (tn.databaseNumber != databaseNumber
                || tn.catalogNumber != catalogNumber
                || tn.collectionNumber != collectionNumber
                || tn.featureNumber != featureNumber) {
                origin = value as? String ?: tn.toString()
                version = null
            } else {
                version = tn.version
                atomic = true
                if (op == CREATE) throw illegalState("CREATE operation must not be used for features that exist and have a state identifier (TupleNumber)")
            }
            return this
        }
        // All other values are treated as origin
        origin = value?.toString()
        return this
    }

