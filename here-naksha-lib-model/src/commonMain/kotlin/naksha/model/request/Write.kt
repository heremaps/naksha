/**
 * A write instruction for the storage.
 *
 * It is **strongly recommended** to use the helper methods to avoid building invalid write instructions.
 *
 * Technically, the storage needs for every write to know where writing should happen, therefore it requires the [databaseId], [catalogId], [collectionId], and the [id]. The new version will be generated by the storage executing the write, so it does not need to be specified, if [version] is given, the current state is expected to exsist in that version _(atomic operation)_.
 *
 * @since 3.0
 */
@JsExport
open class Write : PAnyMap() {

    companion object Write_C {
        /**
         * A special byte-array instance that represents `undefined`.
         * @since 3.0
         */
        private val UNDEFINED_BYTES = "undefined".encodeToByteArray()

        private fun compareCatalogIds(a: String, b: String): Int {
            if (a == b) return 0
            // We order all modifications done in admin-map first.
            if (ADMIN_CATALOG_ID.text == a) return -1
            if (ADMIN_CATALOG_ID.text == b) return 1
            return a.compareTo(b)
        }

        private fun compareCollectionIds(a: String, b: String): Int {
            if (a == b) return 0
            // We order all modifications done in map's collection first (create maps first).
            if (CATALOGS_COL_ID.text == a) return -1
            if (CATALOGS_COL_ID.text == b) return 1
            // We order all modifications done in internal collection's-collection second.
            if (COLLECTIONS_COL_ID.text == a) return -1
            if (COLLECTIONS_COL_ID.text == b) return 1
            // Rest by id
            return a.compareTo(b)
        }

        /**
         * The method to order writes via [MutableList.sortedWith] by:
         * - `catalog-id`
         * - `collection-id`
         * - `partition-number`
         * - `op` (CREATE, UPSERT, UPDATE, DELETE, PURGE, UNKNOWN)
         * - `feature-id`
         *
         * Example:
         * ```kotlin
         * val writes = WriteList()
         * ... add writes
         * writes.sortedWith(Write::sortCompare)
         * ```
         * It is very important that all code that modifies features, use the same ordering.
         *
         * **If writes are not ordered like this, this may lead to concurrent write conflicts and deadlocks in the storage!**
         * @since 3.0
         */
        @JvmStatic
        @JsStatic
        fun sortCompare(a: Write?, b: Write?): Int {
            if (a === b) return 0
            if (b == null) return -1
            if (a == null) return 1

            // Sorts by map-id, collection-id, feature-id.
            // Sorts admin-map, map's collection, and collection's collection first.
            val a_id = a.id
            val b_id = b.id
            val a_catalogId = a.catalogId
            val b_catalogId = b.catalogId
            val a_colId = a.collectionId
            val b_colId = b.collectionId
            val map_diff = compareCatalogIds(a_catalogId.text, b_catalogId.text)
            return if (map_diff == 0) {
                val col_diff = compareCollectionIds(a_colId.text, b_colId.text)
                if (col_diff == 0) {
                    val a_partition = a_id.partitionNumber
                    val b_partition = b_id.partitionNumber
                    val part_diff = a_partition.compareTo(b_partition)
                    if (part_diff == 0) {
                        val id_diff = a_id.compareTo(b_id)
                        if (id_diff == 0) a.op.compareTo(b.op) else id_diff
                    } else part_diff
                } else col_diff
            } else map_diff
        }

